export type Rank = (typeof ui.ranks)[number];

export function rankFor(stars: number): { current: Rank; next: Rank | null } {
  const list = ui.ranks;
  let current: Rank = list[0];
  for (const r of list) if (stars >= r.min) current = r;
  const next = list.find((r) => r.min > stars) ?? null;
  return { current, next };
}
